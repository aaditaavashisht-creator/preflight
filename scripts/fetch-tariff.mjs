/**
 * Bakes the UK Trade Tariff into the bundle at build time.
 *
 * Run on a developer's machine, never in the browser. The shipped app makes no
 * network call at all: this writes two static files that the engine imports, so
 * the rulebook stays a pure function of its arguments and there is nothing to
 * be rate-limited or go down at run time.
 *
 *   node scripts/fetch-tariff.mjs
 *
 * Source: https://www.trade-tariff.service.gov.uk/api/v2
 * Licence: Open Government Licence v3.0 (attribution only).
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const BASE = 'https://www.trade-tariff.service.gov.uk/api/v2';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'lib', 'generated');

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function get(p, attempt = 1) {
  const res = await fetch(`${BASE}${p}`, { headers: { accept: 'application/json' } });
  if (res.status === 429 || res.status >= 500) {
    if (attempt > 4) throw new Error(`${p}: HTTP ${res.status} after ${attempt} attempts`);
    const wait = 2000 * attempt;
    console.log(`  ${p} -> ${res.status}, retrying in ${wait}ms`);
    await sleep(wait);
    return get(p, attempt + 1);
  }
  if (!res.ok) throw new Error(`${p}: HTTP ${res.status}`);
  return res.json();
}

const gz = (s) => zlib.gzipSync(Buffer.from(s), { level: 9 }).length;
const kb = (n) => `${(n / 1024).toFixed(1)} KB`;

/* ---- 1. Every valid 6-digit subheading ---- */

async function subheadings() {
  const codes = new Set();
  for (let section = 1; section <= 21; section += 1) {
    const json = await get(`/goods_nomenclatures/section/${section}`);
    for (const row of json.data ?? []) {
      const id = row.attributes?.goods_nomenclature_item_id;
      if (typeof id !== 'string' || id.length !== 10) continue;
      // A 6-digit subheading is a 10-digit id whose last four are zeroes.
      if (!/^\d{6}0000$/.test(id)) continue;
      codes.add(id.slice(0, 6));
    }
    process.stdout.write(`  section ${String(section).padStart(2)}: ${codes.size} codes so far\n`);
    await sleep(250);
  }
  return [...codes].sort();
}

/* ---- 2. Plain English -> commodity code ---- */

async function references() {
  const json = await get('/search_references');
  /** @type {Map<string, Set<string>>} code -> titles */
  const byCode = new Map();
  for (const row of json.data ?? []) {
    const a = row.attributes ?? {};
    const id = a.goods_nomenclature_item_id;
    const title = (a.title ?? '').trim().toLowerCase();
    if (typeof id !== 'string' || id.length < 6 || !title) continue;
    // Titles that are themselves a code, or absurdly long, help nobody.
    if (/^\d+$/.test(title) || title.length > 48) continue;
    const code = id.slice(0, 6);
    if (!byCode.has(code)) byCode.set(code, new Set());
    byCode.get(code).add(title);
  }
  return byCode;
}

async function main() {
  console.log('Fetching the UK Trade Tariff. This writes static files; the app never calls it.\n');

  console.log('Valid 6-digit subheadings:');
  const codes = await subheadings();
  console.log(`  ${codes.length} subheadings\n`);

  console.log('Plain English search references:');
  const byCode = await references();
  const pairs = [...byCode.values()].reduce((n, s) => n + s.size, 0);
  console.log(`  ${pairs} titles across ${byCode.size} codes\n`);

  // Packed as one string of concatenated 6-digit codes: the engine rebuilds a
  // Set once at module load. Sorted digits compress far better than an array.
  const packed = codes.join('');
  const lookup = Object.fromEntries(
    [...byCode.entries()].sort((a, z) => a[0].localeCompare(z[0]))
      .map(([code, titles]) => [code, [...titles].sort().join('|')]),
  );

  fs.mkdirSync(OUT, { recursive: true });

  const header =
    '// GENERATED by scripts/fetch-tariff.mjs. Do not edit by hand.\n' +
    '// Source: UK Trade Tariff API, https://www.trade-tariff.service.gov.uk\n' +
    '// Licence: Open Government Licence v3.0.\n' +
    `// Fetched: ${new Date().toISOString().slice(0, 10)}\n`;

  const codesTs =
    `${header}\n/** ${codes.length} valid 6-digit subheadings, concatenated. */\n` +
    `export const PACKED_SUBHEADINGS =\n  '${packed}';\n`;
  fs.writeFileSync(path.join(OUT, 'hs-subheadings.ts'), codesTs);

  const lookupJson = JSON.stringify(lookup);
  fs.writeFileSync(path.join(OUT, 'hs-lookup.json'), lookupJson);

  console.log('Written:');
  console.log(`  lib/generated/hs-subheadings.ts  ${kb(codesTs.length)} raw, ${kb(gz(codesTs))} gzipped`);
  console.log(`  lib/generated/hs-lookup.json     ${kb(lookupJson.length)} raw, ${kb(gz(lookupJson))} gzipped`);
}

main().catch((e) => { console.error('\nFailed:', e.message); process.exit(1); });
